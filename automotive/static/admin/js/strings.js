export const STRINGS = { ka: KA, en: EN };
export const LANGUAGES = ['ka', 'en'];

const STORAGE_KEY = 'garage.staff.lang';
const listeners = new Set();

function stored() {
  try {
    const value = window.localStorage.getItem(STORAGE_KEY);
    return LANGUAGES.includes(value) ? value : null;
  } catch {
    return null; // Storage can be blocked; the default language still works.
  }
}

let current = stored() || 'ka';

export function getLang() {
  return current;
}

export function otherLang() {
  return current === 'ka' ? 'en' : 'ka';
}

export function setLang(next) {
  if (!LANGUAGES.includes(next) || next === current) {
    return;
  }
  current = next;
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Not remembered, but applied for this visit.
  }
  document.documentElement.lang = next;
  for (const listener of [...listeners]) {
    listener(next);
  }
}

export function onLangChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function fill(template, values) {
  if (!values) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match));
}

export function has(key) {
  return Object.prototype.hasOwnProperty.call(STRINGS[current], key);
}

export function t(key, values) {
  const table = STRINGS[current];
  const template = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
    : Object.prototype.hasOwnProperty.call(EN, key) ? EN[key] : key;
  return fill(template, values);
}

// One language of a {ka, en} pair from the server, falling back to the other one.
export function pick(pair) {
  if (!pair || typeof pair !== 'object') {
    return '';
  }
  return String(pair[current] || pair[otherLang()] || '');
}
